"""
nmsound.py -- writes and reads NimbleEngine `.nmsound` files without the
editor, byte for byte as Engine/Modules/Audio/Source/Private/Audio/SoundAsset.cpp
serializes them (NSND v1: SHDR, SDAT, SSRC; no ISRC, since the sources here
are generated by build_audio.py rather than imported from a file on disk).

The cook key is computed the same way as ComputeSoundCookKey, so the editor
sees each sound as already cooked and never cooks it again. A Decompressed
sound's samples are made exactly as CookSound makes them from the source
(miniaudio's s16 -> f32 is x / 32768; ToS16 is lround(x * 32767)).

    python nmsound.py <file.nmsound>...     prints what a file holds and
                                            checks its cook key
"""

import struct
import subprocess
import sys

import numpy as np

COOK_VERSION = 1
WAVEFORM_BUCKETS = 128

MODES = {"Auto": 0, "Decompressed": 1, "Compressed": 2, "Stream": 3}
ATTEN = {"None": 0, "Inverse": 1, "Linear": 2, "Exponential": 3}
BUSES = {"Master": 0, "Music": 1, "SFX": 2, "UI": 3, "Voice": 4, "Ambient": 5}
FORMATS = {"Unknown": 0, "Wav": 1, "Flac": 2, "Mp3": 3, "Vorbis": 4}


def tag(s):
    a, b, c, d = (ord(ch) for ch in s)
    return (a << 24) | (b << 16) | (c << 8) | d


T_SOUND, T_HDR, T_DAT, T_SRC = tag("NSND"), tag("SHDR"), tag("SDAT"), tag("SSRC")

FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211
MASK = (1 << 64) - 1


def fnv(h, data):
    for b in data:
        h = ((h ^ b) * FNV_PRIME) & MASK
    return h


def detect_format(src):
    if src[:4] in (b"RIFF", b"RIFX", b"RF64"):
        return "Wav"
    if src[:4] == b"fLaC":
        return "Flac"
    if src[:4] == b"OggS":
        return "Vorbis"
    if src[:3] == b"ID3" or (src[0] == 0xFF and (src[1] & 0xE0) == 0xE0):
        return "Mp3"
    return "Unknown"


def cook_key(source, s):
    h = fnv(FNV_OFFSET, struct.pack("<Q", COOK_VERSION))
    h = fnv(h, struct.pack("<Q", len(source)))
    h = fnv(h, source)
    h = fnv(h, struct.pack("<BBIBB", MODES[s["LoadMode"]], int(s["ForceMono"]), s["SampleRate"],
                           int(s["TrimSilence"]), int(s["Normalize"])))
    return 1 if h == 0 else h


DEFAULTS = dict(LoadMode="Auto", ForceMono=True, SampleRate=0, TrimSilence=False, Normalize=False,
                Volume=1.0, Pitch=1.0, Loop=False, Bus="SFX", Spatial=True, MinDistance=100.0,
                MaxDistance=5000.0, Attenuation="Inverse", Rolloff=1.0, Doppler=1.0,
                ConeInner=360.0, ConeOuter=360.0, ConeOuterGain=0.0)


def decode_f32(source):
    """Decodes a source with ffmpeg to float32 at its own rate and channels."""
    probe = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "a:0", "-show_entries",
                            "stream=sample_rate,channels", "-of", "csv=p=0", "-i", "pipe:0"],
                           input=source, capture_output=True, check=True).stdout.decode().split(",")
    rate, ch = int(probe[0]), int(probe[1])
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "pipe:0", "-f", "f32le", "-acodec", "pcm_f32le", "-"],
                         input=source, capture_output=True, check=True).stdout
    pcm = np.frombuffer(raw, dtype="<f4").reshape(-1, ch)
    return pcm, rate


def waveform(pcm):
    frames = len(pcm)
    a = np.abs(pcm).max(axis=1) if pcm.ndim == 2 else np.abs(pcm)
    out = bytearray(WAVEFORM_BUCKETS)
    for b in range(WAVEFORM_BUCKETS):
        lo = frames * b // WAVEFORM_BUCKETS
        hi = min(max(frames * (b + 1) // WAVEFORM_BUCKETS, lo + 1), frames)
        pk = float(a[lo:hi].max()) if hi > lo else 0.0
        out[b] = int(np.floor(min(pk, 1.0) * 255.0 + 0.5))
    return bytes(out)


class Writer:
    def __init__(self):
        self.b = bytearray()
        self.stack = []

    def open(self, t, ver=1):
        self.b += struct.pack("<IH", t, ver)
        self.stack.append(len(self.b))
        self.b += b"\0\0\0\0"

    def close(self):
        at = self.stack.pop()
        struct.pack_into("<I", self.b, at, len(self.b) - at - 4)

    def put(self, fmt, *v):
        self.b += struct.pack("<" + fmt, *v)


def build(source, settings, pcm16_mono48k=None, cook_mode=None):
    """
    The bytes of a .nmsound for `source` (a FLAC/WAV/Ogg/MP3 file's bytes).

    Decompressed: pcm16_mono48k must be the int16 samples the source decodes
    to (mono, 48 kHz), so nothing is resampled. Other modes decode the source
    with ffmpeg for its length, peak and waveform.
    """
    s = {**DEFAULTS, **settings}
    mode = cook_mode or s["LoadMode"]
    assert mode in ("Decompressed", "Compressed", "Stream"), "Auto needs cook_mode: what Auto chose"
    fmt = detect_format(source)

    if mode == "Decompressed":
        assert s["ForceMono"] and s["SampleRate"] in (0, 48000) and not s["TrimSilence"]
        v = np.asarray(pcm16_mono48k, dtype=np.int16)
        f = v.astype(np.float32) * np.float32(1.0 / 32768.0)
        cooked = np.clip(np.floor(f * np.float32(32767.0) + np.float32(0.5)), -32767, 32767).astype("<i2")
        # lround rounds half away from zero; floor(x+0.5) differs only on negative halves.
        neg_half = (f < 0) & (np.abs(f * np.float32(32767.0) - np.trunc(f * np.float32(32767.0))) == 0.5)
        cooked[neg_half] -= 1
        channels, rate, frames = 1, 48000, len(v)
        peak = float(min(np.abs(f).max(), 1.0))
        wave = waveform(f)
        samples = cooked.tobytes()
    else:
        pcm, rate = decode_f32(source)
        channels, frames = pcm.shape[1], pcm.shape[0]
        peak = float(min(np.abs(pcm).max(), 1.0))
        wave = waveform(pcm)
        samples = b""

    gain = min(1.0 / peak, 16.0) if s["Normalize"] and peak > 0 else 1.0
    key = cook_key(source, s)

    w = Writer()
    w.open(T_SOUND)
    w.open(T_HDR)
    w.put("BBB I BB", FORMATS[fmt], MODES[s["LoadMode"]], int(s["ForceMono"]), s["SampleRate"], int(s["TrimSilence"]),
          int(s["Normalize"]))
    w.put("ff B B B", s["Volume"], s["Pitch"], int(s["Loop"]), BUSES[s["Bus"]], int(s["Spatial"]))
    w.put("ff B ff fff", s["MinDistance"], s["MaxDistance"], ATTEN[s["Attenuation"]], s["Rolloff"], s["Doppler"],
          s["ConeInner"], s["ConeOuter"], s["ConeOuterGain"])
    w.close()
    w.open(T_DAT)
    w.put("Q B I I Q ff", key, MODES[mode], channels, rate, frames, peak, gain)
    w.put("I", len(wave))
    w.b += wave
    w.put("Q", len(samples) // 2)
    w.b += samples
    w.close()
    w.open(T_SRC)
    w.put("Q", len(source))
    w.b += source
    w.close()
    w.close()
    return bytes(w.b), frames / rate


def read(data):
    """Parses a .nmsound; returns (settings, cooked, source)."""
    pos = 0

    def chunk(expect):
        nonlocal pos
        t, ver, size = struct.unpack_from("<IHI", data, pos)
        assert t == expect, f"chunk {t:08x} != {expect:08x}"
        pos += 10
        return pos + size

    def get(fmt):
        nonlocal pos
        v = struct.unpack_from("<" + fmt, data, pos)
        pos += struct.calcsize("<" + fmt)
        return v

    end_all = chunk(T_SOUND)
    end = chunk(T_HDR)
    inv = lambda d, v: next(k for k, x in d.items() if x == v)
    fmt, mode, mono, rate, trim, norm = get("BBBIBB")
    vol, pitch, loop, bus, spatial = get("ffBBB")
    mind, maxd, att, roll, dop, ci, co, cg = get("ffBfffff")
    s = dict(Format=inv(FORMATS, fmt), LoadMode=inv(MODES, mode), ForceMono=bool(mono), SampleRate=rate,
             TrimSilence=bool(trim), Normalize=bool(norm), Volume=vol, Pitch=pitch, Loop=bool(loop),
             Bus=inv(BUSES, bus), Spatial=bool(spatial), MinDistance=mind, MaxDistance=maxd,
             Attenuation=inv(ATTEN, att), Rolloff=roll, Doppler=dop, ConeInner=ci, ConeOuter=co, ConeOuterGain=cg)
    pos = end
    end = chunk(T_DAT)
    key, cmode, ch, crate, frames, peak, gain = get("QBIIQff")
    (nw,) = get("I")
    pos += nw
    (ns,) = get("Q")
    samples = np.frombuffer(data, dtype="<i2", count=ns, offset=pos)
    pos = end
    source = b""
    if pos < end_all and struct.unpack_from("<I", data, pos)[0] == T_SRC:
        end = chunk(T_SRC)
        (n,) = get("Q")
        source = data[pos:pos + n]
        pos = end
    c = dict(Key=key, Mode=inv(MODES, cmode), Channels=ch, Rate=crate, Frames=frames, Peak=peak, Gain=gain,
             Samples=len(samples))
    return s, c, source, samples


if __name__ == "__main__":
    for path in sys.argv[1:]:
        data = open(path, "rb").read()
        s, c, src, _ = read(data)
        ok = c["Key"] == cook_key(src, s)
        print(f"{path}: {c['Mode']} {c['Channels']}ch {c['Rate']} Hz {c['Frames'] / c['Rate']:.2f} s "
              f"bus={s['Bus']} loop={s['Loop']} 3D={s['Spatial']} src={s['Format']} {len(src)} B "
              f"key {'OK' if ok else 'MISMATCH'}")
